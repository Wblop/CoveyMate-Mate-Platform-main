CREATE TABLE IF NOT EXISTS app.audit_events
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    action_code     TEXT        NOT NULL,
    action_group    TEXT        NOT NULL,
    action_label    TEXT        NOT NULL,
    description     TEXT        NULL,
    source          TEXT        NOT NULL,
    actor_type      TEXT        NOT NULL,
    actor_user_id   UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    actor_email     TEXT        NULL,
    actor_name      TEXT        NULL,
    subject_user_id UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    subject_email   TEXT        NULL,
    subject_name    TEXT        NULL,
    entity_type     TEXT        NULL,
    entity_id       TEXT        NULL,
    entity_label    TEXT        NULL,
    request_path    TEXT        NULL,
    request_method  TEXT        NULL,
    ip_address      TEXT        NULL,
    user_agent      TEXT        NULL,
    metadata_json   JSONB       NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_audit_events_source
        CHECK (source IN ('server', 'client')),
    CONSTRAINT ck_audit_events_actor_type
        CHECK (actor_type IN ('user', 'admin', 'conveyancer', 'anonymous', 'system'))
);

CREATE INDEX IF NOT EXISTS ix_audit_events_occurred_at_id
    ON app.audit_events (occurred_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_action_code_occurred_at
    ON app.audit_events (action_code, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_action_group_occurred_at
    ON app.audit_events (action_group, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_actor_user_occurred_at
    ON app.audit_events (actor_user_id, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_subject_user_occurred_at
    ON app.audit_events (subject_user_id, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_actor_type_occurred_at
    ON app.audit_events (actor_type, occurred_at DESC);

CREATE INDEX IF NOT EXISTS ix_audit_events_actor_email_lower
    ON app.audit_events ((LOWER(actor_email)));

CREATE INDEX IF NOT EXISTS ix_audit_events_subject_email_lower
    ON app.audit_events ((LOWER(subject_email)));
