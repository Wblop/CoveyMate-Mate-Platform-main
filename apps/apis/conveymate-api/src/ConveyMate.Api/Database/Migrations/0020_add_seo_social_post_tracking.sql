ALTER TABLE app.seo_engine_jobs
    DROP CONSTRAINT IF EXISTS ck_seo_engine_jobs_type;

ALTER TABLE app.seo_engine_jobs
    ADD CONSTRAINT ck_seo_engine_jobs_type
        CHECK (job_type IN ('generate-article', 'publish-next-article', 'refresh-sitemap'));

CREATE TABLE IF NOT EXISTS app.seo_engine_article_social_posts
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id       UUID        NOT NULL REFERENCES app.seo_engine_articles (id) ON DELETE CASCADE,
    channel          TEXT        NOT NULL,
    status           TEXT        NOT NULL DEFAULT 'pending',
    lease_token      UUID        NULL,
    planned_content  TEXT        NOT NULL DEFAULT '',
    attempt_count    INTEGER     NOT NULL DEFAULT 0,
    external_post_id TEXT        NULL,
    external_url     TEXT        NULL,
    published_at     TIMESTAMPTZ NULL,
    last_attempt_at  TIMESTAMPTZ NULL,
    last_error       TEXT        NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_seo_engine_article_social_posts_channel
        CHECK (channel IN ('x')),
    CONSTRAINT ck_seo_engine_article_social_posts_status
        CHECK (status IN ('pending', 'publishing', 'published', 'failed', 'skipped'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_seo_engine_article_social_posts_article_channel
    ON app.seo_engine_article_social_posts (article_id, channel);

CREATE INDEX IF NOT EXISTS ix_seo_engine_article_social_posts_channel_status_created
    ON app.seo_engine_article_social_posts (channel, status, created_at DESC);

DROP TRIGGER IF EXISTS trg_seo_engine_article_social_posts_set_updated_at ON app.seo_engine_article_social_posts;
CREATE TRIGGER trg_seo_engine_article_social_posts_set_updated_at
    BEFORE UPDATE
    ON app.seo_engine_article_social_posts
    FOR EACH ROW
EXECUTE FUNCTION app.set_updated_at();

INSERT INTO app.seo_engine_article_social_posts
(
    article_id,
    channel,
    status,
    planned_content,
    published_at,
    last_error
)
SELECT articles.id,
       'x',
       'skipped',
       'Historical article skipped during X rollout.',
       NOW(),
       'Seeded during X rollout baseline.'
FROM app.seo_engine_articles articles
WHERE articles.status = 'published'
ON CONFLICT (article_id, channel) DO NOTHING;
