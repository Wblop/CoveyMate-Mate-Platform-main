CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE TABLE IF NOT EXISTS app.seo_engine_articles
(
    id                       UUID        PRIMARY KEY,
    status                   TEXT        NOT NULL DEFAULT 'draft',
    title                    TEXT        NOT NULL,
    slug                     TEXT        NOT NULL,
    excerpt                  TEXT        NOT NULL DEFAULT '',
    body_markdown            TEXT        NOT NULL,
    body_html                TEXT        NOT NULL,
    body_plain_text          TEXT        NOT NULL,
    body_fingerprint_sha256  TEXT        NOT NULL,
    meta_title               TEXT        NOT NULL DEFAULT '',
    meta_description         TEXT        NOT NULL DEFAULT '',
    tags_json                JSONB       NOT NULL DEFAULT '[]'::jsonb,
    keywords_json            JSONB       NOT NULL DEFAULT '[]'::jsonb,
    duplicate_warnings_json  JSONB       NOT NULL DEFAULT '[]'::jsonb,
    source_count             INTEGER     NOT NULL DEFAULT 0,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_generated_at        TIMESTAMPTZ NULL,
    published_at             TIMESTAMPTZ NULL,
    deleted_at               TIMESTAMPTZ NULL,
    created_by_user_id       UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    updated_by_user_id       UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    published_by_user_id     UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    CONSTRAINT ck_seo_engine_articles_status
        CHECK (status IN ('draft', 'published', 'deleted'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_seo_engine_articles_slug_active
    ON app.seo_engine_articles (LOWER(slug))
    WHERE status <> 'deleted';

CREATE INDEX IF NOT EXISTS ix_seo_engine_articles_status_published_created
    ON app.seo_engine_articles (status, published_at DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_seo_engine_articles_title_trgm
    ON app.seo_engine_articles
    USING gin (LOWER(title) gin_trgm_ops);

CREATE INDEX IF NOT EXISTS ix_seo_engine_articles_body_plain_trgm
    ON app.seo_engine_articles
    USING gin (LOWER(body_plain_text) gin_trgm_ops);

DROP TRIGGER IF EXISTS trg_seo_engine_articles_set_updated_at ON app.seo_engine_articles;
CREATE TRIGGER trg_seo_engine_articles_set_updated_at
    BEFORE UPDATE
    ON app.seo_engine_articles
    FOR EACH ROW
EXECUTE FUNCTION app.set_updated_at();

CREATE TABLE IF NOT EXISTS app.seo_engine_article_sections
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id      UUID        NOT NULL REFERENCES app.seo_engine_articles (id) ON DELETE CASCADE,
    position        INTEGER     NOT NULL,
    section_id      TEXT        NOT NULL,
    heading         TEXT        NOT NULL,
    paragraphs_json JSONB       NOT NULL DEFAULT '[]'::jsonb,
    bullets_json    JSONB       NOT NULL DEFAULT '[]'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_seo_engine_article_sections_article_section
    ON app.seo_engine_article_sections (article_id, section_id);

CREATE INDEX IF NOT EXISTS ix_seo_engine_article_sections_article_position
    ON app.seo_engine_article_sections (article_id, position);

CREATE TABLE IF NOT EXISTS app.seo_engine_article_sources
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id    UUID        NOT NULL REFERENCES app.seo_engine_articles (id) ON DELETE CASCADE,
    position      INTEGER     NOT NULL,
    source_name   TEXT        NOT NULL,
    publisher     TEXT        NOT NULL DEFAULT '',
    headline      TEXT        NOT NULL,
    source_url    TEXT        NOT NULL,
    published_at  TIMESTAMPTZ NULL,
    summary       TEXT        NOT NULL DEFAULT '',
    content_hash  TEXT        NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_seo_engine_article_sources_article_position
    ON app.seo_engine_article_sources (article_id, position);

CREATE INDEX IF NOT EXISTS ix_seo_engine_article_sources_url
    ON app.seo_engine_article_sources (LOWER(source_url));

CREATE TABLE IF NOT EXISTS app.seo_engine_source_cache
(
    canonical_url TEXT        NOT NULL,
    content_hash  TEXT        NOT NULL,
    source_name   TEXT        NOT NULL DEFAULT '',
    publisher     TEXT        NOT NULL DEFAULT '',
    headline      TEXT        NOT NULL DEFAULT '',
    source_url    TEXT        NOT NULL DEFAULT '',
    published_at  TIMESTAMPTZ NULL,
    summary       TEXT        NOT NULL,
    captured_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (canonical_url, content_hash)
);

CREATE INDEX IF NOT EXISTS ix_seo_engine_source_cache_captured_at
    ON app.seo_engine_source_cache (captured_at DESC);

CREATE TABLE IF NOT EXISTS app.seo_engine_jobs
(
    id                   UUID        PRIMARY KEY,
    job_type             TEXT        NOT NULL,
    status               TEXT        NOT NULL DEFAULT 'pending',
    requested_source     TEXT        NOT NULL,
    requested_by_user_id UUID        NULL REFERENCES app.users (id) ON DELETE SET NULL,
    requested_by_email   TEXT        NULL,
    requested_by_name    TEXT        NULL,
    article_id           UUID        NULL REFERENCES app.seo_engine_articles (id) ON DELETE SET NULL,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at           TIMESTAMPTZ NULL,
    completed_at         TIMESTAMPTZ NULL,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    error_message        TEXT        NULL,
    CONSTRAINT ck_seo_engine_jobs_type
        CHECK (job_type IN ('generate-article', 'refresh-sitemap')),
    CONSTRAINT ck_seo_engine_jobs_status
        CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    CONSTRAINT ck_seo_engine_jobs_requested_source
        CHECK (requested_source IN ('admin', 'scheduler', 'system'))
);

CREATE INDEX IF NOT EXISTS ix_seo_engine_jobs_created_at
    ON app.seo_engine_jobs (created_at DESC);

CREATE INDEX IF NOT EXISTS ix_seo_engine_jobs_status_created_at
    ON app.seo_engine_jobs (status, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_seo_engine_jobs_type_created_at
    ON app.seo_engine_jobs (job_type, created_at DESC);

DROP TRIGGER IF EXISTS trg_seo_engine_jobs_set_updated_at ON app.seo_engine_jobs;
CREATE TRIGGER trg_seo_engine_jobs_set_updated_at
    BEFORE UPDATE
    ON app.seo_engine_jobs
    FOR EACH ROW
EXECUTE FUNCTION app.set_updated_at();
